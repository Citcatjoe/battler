import { attacksOf, finalState, MAX_TURNS, simulateCombat, type Beat, type CombatResult, type Pair } from './combat'
import type { CharacterEvent } from './events'
import { seededRng } from './rng'
import { CHARACTER_IDS, CHARACTERS, createCharacter } from './roster'
import { computeStats } from './stats'
